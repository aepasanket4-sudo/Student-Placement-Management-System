  SELECT s.student_id,
       s.student_name,
       d.department_name,
       c.company_name,
       j.job_title,
       p.package_lpa,
       p.placement_date
FROM placements p
JOIN students s
    ON p.student_id = s.student_id
JOIN departments d
    ON s.department_id = d.department_id
JOIN companies c
    ON p.company_id = c.company_id
JOIN jobs j
    ON p.job_id = j.job_id
;
