--  DDL for Procedure PROC_STUDENT_APPLICATIONS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "PLACEMENT_ADMIN"."PROC_STUDENT_APPLICATIONS" (
    p_student_id IN NUMBER
)
AS
BEGIN
    FOR rec IN (
        SELECT s.student_name,
               c.company_name,
               j.job_title,
               a.status
        FROM applications a
        JOIN students s
            ON a.student_id = s.student_id
        JOIN jobs j
            ON a.job_id = j.job_id
        JOIN companies c
            ON j.company_id = c.company_id
        WHERE s.student_id = p_student_id
    )
    LOOP
        DBMS_OUTPUT.PUT_LINE(
            rec.student_name || ' | ' ||
            rec.company_name || ' | ' ||
            rec.job_title || ' | ' ||
            rec.status
        );
    END LOOP;
END;

